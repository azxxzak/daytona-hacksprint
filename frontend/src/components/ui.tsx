"use client";

import Link from "next/link";
import { useEffect, useRef, useState, type ButtonHTMLAttributes, type ReactNode } from "react";
import { X } from "lucide-react";
import { useI18n } from "./i18n-provider";

export function cx(...a: (string | false | null | undefined)[]): string {
  return a.filter(Boolean).join(" ");
}

type Variant = "primary" | "outline" | "dark" | "ghost";

const base =
  "inline-flex items-center justify-center gap-2 rounded-full font-medium whitespace-nowrap select-none transition-colors disabled:opacity-40 disabled:cursor-not-allowed";
const variants: Record<Variant, string> = {
  primary: "bg-ink text-white hover:bg-black [&_svg]:text-lime",
  dark: "bg-ink/80 text-white backdrop-blur-sm hover:bg-ink [&_svg]:text-lime",
  outline: "bg-surface text-ink border border-ink/80 hover:bg-ink hover:text-white",
  ghost: "text-ink hover:bg-ink/5",
};
const sizes = { sm: "h-8 px-3.5 text-[13px]", md: "h-10 px-5 text-sm", lg: "h-12 px-7 text-[15px]" };

export function buttonClass(variant: Variant = "primary", size: keyof typeof sizes = "md", extra?: string) {
  return cx(base, variants[variant], sizes[size], extra);
}

export function Button({
  variant = "primary",
  size = "md",
  className,
  type = "button",
  ...rest
}: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant; size?: keyof typeof sizes }) {
  return <button type={type} className={buttonClass(variant, size, className)} {...rest} />;
}

export function LinkButton({
  href,
  variant = "primary",
  size = "md",
  className,
  children,
}: {
  href: string;
  variant?: Variant;
  size?: keyof typeof sizes;
  className?: string;
  children: ReactNode;
}) {
  return (
    <Link href={href} className={buttonClass(variant, size, className)}>
      {children}
    </Link>
  );
}

/** Tiny label, large bold title, 2px black rule, optional action on the right. */
export function SectionHeader({
  label,
  title,
  action,
  as: H = "h2",
}: {
  label?: string;
  title: string;
  action?: ReactNode;
  as?: "h1" | "h2" | "h3";
}) {
  return (
    <div className="flex items-end justify-between gap-4 border-b-2 border-ink pb-3">
      <div className="min-w-0">
        {label && <p className="text-[11px] font-medium uppercase tracking-[0.12em] text-mute">{label}</p>}
        <H className="text-2xl font-bold leading-tight tracking-tight sm:text-[28px]">{title}</H>
      </div>
      {action && <div className="shrink-0">{action}</div>}
    </div>
  );
}

export function Card({ className, ...rest }: React.HTMLAttributes<HTMLDivElement>) {
  return <div className={cx("rounded-card bg-surface", className)} {...rest} />;
}

export function Spinner({ className }: { className?: string }) {
  return (
    <span
      aria-hidden
      className={cx("inline-block size-4 rounded-full border-2 border-current border-t-transparent motion-safe:animate-spin", className)}
    />
  );
}

/** Soft portrait with a calm placeholder until the (possibly slow, first-time generated) image arrives. */
export function Avatar({
  src,
  name,
  color,
  className,
  rounded = "rounded-none",
  eager,
}: {
  src: string;
  name: string;
  color?: string;
  className?: string;
  rounded?: string;
  eager?: boolean;
}) {
  const [state, setState] = useState<"loading" | "ok" | "error">("loading");
  const [attempt, setAttempt] = useState(0);
  const ref = useRef<HTMLImageElement>(null);

  useEffect(() => {
    const el = ref.current;
    if (el?.complete && el.naturalWidth > 0) setState("ok");
  }, []);

  useEffect(() => {
    if (state !== "error" || attempt >= 2) return;
    const id = setTimeout(() => {
      setAttempt((a) => a + 1);
      setState("loading");
    }, 4000);
    return () => clearTimeout(id);
  }, [state, attempt]);

  const url = attempt ? `${src}${src.includes("?") ? "&" : "?"}r=${attempt}` : src;
  return (
    <div className={cx("relative overflow-hidden bg-[#e9e9ec]", rounded, className)}>
      {state !== "ok" && (
        <div
          aria-hidden
          className={cx("absolute inset-0 grid place-items-center text-lg font-medium text-mute/70", state === "loading" && "pulse")}
          style={color ? { background: `${color}14` } : undefined}
        >
          {name.slice(0, 1)}
        </div>
      )}
      {/* eslint-disable-next-line @next/next/no-img-element -- portraits are generated by the API; next/image would re-proxy them */}
      <img
        ref={ref}
        src={url}
        alt={name}
        loading={eager ? "eager" : "lazy"}
        decoding="async"
        onLoad={() => setState("ok")}
        onError={() => setState("error")}
        className={cx("absolute inset-0 h-full w-full object-cover transition-opacity duration-500", state === "ok" ? "opacity-100" : "opacity-0")}
      />
    </div>
  );
}

/** Native <dialog>: focus trap, Escape and focus restore come from the platform. */
export function Dialog({
  open,
  onClose,
  label,
  side,
  children,
}: {
  open: boolean;
  onClose: () => void;
  label: string;
  side?: boolean;
  children: ReactNode;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  const { t } = useI18n();

  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (open && !d.open) d.showModal();
    if (!open && d.open) d.close();
  }, [open]);

  useEffect(() => {
    if (!open) return;
    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = prev;
    };
  }, [open]);

  return (
    <dialog
      ref={ref}
      aria-label={label}
      onClose={onClose}
      onClick={(e) => {
        if (e.target === ref.current) onClose();
      }}
      className={cx(
        "max-h-none bg-transparent p-0 text-ink",
        side ? "m-0 ml-auto h-dvh w-full max-w-[460px]" : "m-auto w-[min(92vw,420px)] max-w-none",
      )}
    >
      {open && (
        <div
          className={cx(
            "relative bg-surface",
            side ? "sheet h-full overflow-y-auto rounded-l-[20px] p-6 sm:p-8" : "fade-in rounded-card p-6",
          )}
        >
          <button
            type="button"
            onClick={onClose}
            aria-label={t("common.close")}
            className="absolute right-4 top-4 grid size-9 place-items-center rounded-full text-mute hover:bg-ink/5 hover:text-ink"
          >
            <X size={18} aria-hidden />
          </button>
          {children}
        </div>
      )}
    </dialog>
  );
}

export function ErrorNote({ children, action }: { children: ReactNode; action?: ReactNode }) {
  return (
    <div role="alert" className="flex flex-wrap items-center gap-3 rounded-card border border-danger/30 bg-surface px-4 py-3 text-sm text-danger">
      <span className="min-w-0 flex-1">{children}</span>
      {action}
    </div>
  );
}
